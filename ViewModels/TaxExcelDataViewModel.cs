    private static string SanitizeColumnName(string colName)
    {
        if (string.IsNullOrEmpty(colName))
            return "Column";

        var result = colName
            .Replace("、", "")
            .Replace("（", "")
            .Replace("）", "")
            .Replace("【", "")
            .Replace("】", "")
            .Replace("《", "")
            .Replace("》", "")
            .Replace("，", "")
            .Replace("。", "")
            .Replace("；", "")
            .Replace("：", "")
            .Replace("？", "")
            .Replace("！", "")
            .Replace("…", "")
            .Replace("·", "")
            .Replace("'", "")
            .Replace("\"", "")
            .Replace("/", "_")
            .Replace("\\", "_")
            .Replace("(", "")
            .Replace(")", "")
            .Replace("[", "")
            .Replace("]", "")
            .Replace("<", "")
            .Replace(">", "")
            .Replace("*", "")
