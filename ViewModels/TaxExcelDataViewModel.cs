                })
                .DisposeWith(_subscriptions);

            ImportCommand.ThrownExceptions
                .ObserveOn(RxApp.MainThreadScheduler)
                .Subscribe(ex =>
                {
                    SetStatus($"导入失败: {ex.Message}", new SolidColorBrush(Colors.Red));
                })
                .DisposeWith(_subscriptions);

            // 初始化数据
            CanImport = false;
            
            // 监听表名变化
            this.WhenAnyValue(x => x.TableName)
                .Subscribe(_ => ValidateTableName())
                .DisposeWith(_subscriptions);
            
            // 监听数据字典选择变化
            this.WhenAnyValue(x => x.SelectedDictionary)
                .Subscribe(_ => 
                {
                    if (UseDictionary && SelectedDictionary != null && !string.IsNullOrEmpty(_currentFileName))
                    {
                        GenerateTableName();
                    }
                })
                .DisposeWith(_subscriptions);
            
            // 监听是否使用数据字典
            this.WhenAnyValue(x => x.UseDictionary)
                .Subscribe(_ => 
                {
                    if (UseDictionary && SelectedDictionary != null && !string.IsNullOrEmpty(_currentFileName))
                    {
                        GenerateTableName();
                    }
                    else if (!UseDictionary && !string.IsNullOrEmpty(_currentFileName))
                    {
                        GenerateTableName();
                    }
                })
                .DisposeWith(_subscriptions);
            
            // 初始化
            _ = InitializeAsync();
            
        }
        catch (Exception ex)
        {
            SetStatusSafe($"初始化失败: {ex.Message}", new SolidColorBrush(Colors.Red));
        }
    }

