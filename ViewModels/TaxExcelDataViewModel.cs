    /// <summary>
    /// 解析文件信息（行数、列数、总金额）
    /// </summary>
    private async Task ParseFileInfoAsync()
    {
        if (_disposed || _isCleaned || string.IsNullOrEmpty(FilePath)) return;
        if (_excelService == null) return;

        try
        {
            await ThreadingHelper.RunOnUIThreadAsync(() =>
            {
                if (_disposed || _isCleaned) return;
                IsLoading = true;
                LoadingMessage = "正在解析文件信息...";
                SetStatus("正在解析文件信息...", new SolidColorBrush(Colors.Orange));
            });

            var rawData = await _excelService.ReadExcelAsync(FilePath);

            if (rawData == null || rawData.Count == 0)
            {
                await ShowMessageBoxAsync("文件为空或格式不正确");
                await ThreadingHelper.RunOnUIThreadAsync(() =>
                {
                    if (!_disposed && !_isCleaned) 
                    {
                        IsLoading = false;
                        LoadingMessage = string.Empty;
                    }
                });
                return;
            }

            // 解析税务数据
            var parsedData = ParseTaxExcelData(rawData);

            await ThreadingHelper.RunOnUIThreadAsync(() =>
            {
                if (_disposed || _isCleaned) return;

                int totalRows = parsedData.Count - 1;
                int totalCols = parsedData.Count > 0 && parsedData[0] != null ? parsedData[0].Count : 0;
                ColumnCount = totalCols;
                TotalRows = totalRows;
                
                // 计算总金额
                CalculateTotalAmount(parsedData);
                
                CanImport = true;
                IsLoading = false;
                LoadingMessage = string.Empty;
                SetStatus($"文件解析成功: {Path.GetFileName(FilePath)}，共 {totalRows} 行数据", new SolidColorBrush(Colors.Green));
            });
        }
        catch (Exception ex)
        {
            await ThreadingHelper.RunOnUIThreadAsync(() =>
            {
                if (_disposed || _isCleaned) return;
                CanImport = false;
                IsLoading = false;
                LoadingMessage = string.Empty;
                SetStatus($"解析失败: {ex.Message}", new SolidColorBrush(Colors.Red));
            });
            await ShowMessageBoxAsync($"解析文件信息失败: {ex.Message}");
        }
    }

    /// <summary>
    /// 解析税务Excel数据
    /// </summary>
    private List<List<object>> ParseTaxExcelData(List<List<object>> rawData)
    {
        if (rawData == null || rawData.Count == 0)
            return new List<List<object>>();

        var result = new List<List<object>>();
        var headerIndex = Math.Min(HeaderRowIndex - 1, rawData.Count - 1);
        if (headerIndex < 0) headerIndex = 0;
        
        // 获取表头
        var headerRow = rawData[headerIndex];
        result.Add(headerRow);
        
        // 从表头下一行开始遍历
        for (int i = headerIndex + 1; i < rawData.Count; i++)
        {
            var row = rawData[i];
            if (row == null || row.Count == 0)
                continue;
            
            // 检查是否为空行
            if (IsEmptyRow(row))
                continue;
            
            // 检查是否为合计行
            if (SkipTotalRow && IsTotalRow(row))
                continue;
            
            // 检查是否为结束行
            if (IsEndRow(row))
                break;
            
            result.Add(row);
        }
        
        return result;
    }

    private bool IsEmptyRow(List<object> row)
    {
        if (row == null) return true;
        foreach (var cell in row)
        {
            if (cell != null && !string.IsNullOrEmpty(cell.ToString()?.Trim()))
                return false;
        }
        return true;
    }

    private bool IsTotalRow(List<object> row)
    {
        if (row == null || row.Count == 0)
            return false;
        
        foreach (var cell in row)
        {
            var cellStr = cell?.ToString() ?? string.Empty;
            if (!string.IsNullOrEmpty(cellStr) && 
                cellStr.Contains(SelectedTotalKeyword, StringComparison.OrdinalIgnoreCase))
                return true;
        }
        
        return false;
    }

    private bool IsEndRow(List<object> row)
    {
        if (row == null || row.Count == 0)
            return false;
        
        foreach (var cell in row)
        {
            var cellStr = cell?.ToString() ?? string.Empty;
            if (!string.IsNullOrEmpty(cellStr) && 
                cellStr.Contains(SelectedEndKeyword, StringComparison.OrdinalIgnoreCase))
                return true;
        }
        
        return false;
    }

    private void CalculateTotalAmount(List<List<object>> data)
    {
        if (data == null || data.Count <= 1 || data[0] == null)
        {
            TotalAmount = "0.00";
            return;
        }

        var headers = data[0];
        int amountColIndex = -1;
        
        for (int i = 0; i < headers.Count; i++)
        {
            var header = headers[i]?.ToString() ?? string.Empty;
            if (header.Contains(SelectedAmountKeyword, StringComparison.OrdinalIgnoreCase))
            {
                amountColIndex = i;
                break;
            }
        }
        
        if (amountColIndex < 0)
        {
            TotalAmount = "0.00";
            return;
        }
        
        decimal total = 0;
        for (int i = 1; i < data.Count; i++)
        {
            if (data[i] != null && data[i].Count > amountColIndex)
            {
                var val = data[i][amountColIndex]?.ToString()?.Trim() ?? "0";
                val = val.Replace(",", "").Replace("，", "");
                if (decimal.TryParse(val, out decimal num))
                {
                    total += num;
                }
            }
        }
        
        TotalAmount = total.ToString("N2");
    }

