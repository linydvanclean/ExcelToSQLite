/// <summary>
/// 生成结构签名（用于比较表结构）
/// </summary>
private string GenerateStructureSignature(List<string> columns)
{
    if (columns == null || columns.Count == 0)
        return string.Empty;
    
    // 按列名排序并拼接，确保相同列集合产生相同签名
    var sortedColumns = columns.Select(c => c.ToLowerInvariant()).OrderBy(c => c);
    return string.Join("|", sortedColumns);
}

/// <summary>
/// 比较两列是否相等
/// </summary>
private bool AreColumnsEqual(List<string> columns1, List<string> columns2)
{
    if (columns1 == null && columns2 == null) return true;
    if (columns1 == null || columns2 == null) return false;
    if (columns1.Count != columns2.Count) return false;
    
    // 忽略大小写比较
    for (int i = 0; i < columns1.Count; i++)
    {
        if (!string.Equals(columns1[i], columns2[i], StringComparison.OrdinalIgnoreCase))
            return false;
    }
    return true;
}

/// <summary>
/// 从文件名生成规范的表名（用于多文件导入时的独立表名）
/// </summary>
private string GenerateTableNameFromFileName(string fileName, string baseTableName)
{
    if (string.IsNullOrEmpty(fileName))
        return $"{baseTableName}_File";

    // 1. 清理文件名（替换非法字符为下划线）
    var cleanName = fileName
        .Replace(" ", "_")
        .Replace("-", "_")
        .Replace("/", "_")
        .Replace("\\", "_")
        .Replace(":", "_")
        .Replace("*", "_")
        .Replace("?", "_")
        .Replace("\"", "_")
        .Replace("<", "_")
        .Replace(">", "_")
        .Replace("|", "_")
        .Replace("'", "_")
        .Replace(";", "_")
        .Replace("(", "_")
        .Replace(")", "_")
        .Replace("[", "_")
        .Replace("]", "_")
        .Replace("{", "_")
        .Replace("}", "_")
        .Replace("+", "_")
        .Replace("=", "_")
        .Replace("&", "_")
        .Replace("%", "_")
        .Replace("#", "_")
        .Replace("@", "_")
        .Replace("!", "_")
        .Replace("$", "_")
        .Replace("`", "_")
        .Replace("~", "_")
        .Replace("^", "_");

    // 2. 合并多个下划线
    while (cleanName.Contains("__"))
        cleanName = cleanName.Replace("__", "_");

    // 3. 去除首尾下划线
    cleanName = cleanName.Trim('_');

    // 4. 如果为空，使用默认名称
    if (string.IsNullOrEmpty(cleanName))
        return $"{baseTableName}_File";

    // 5. 如果以数字开头，添加 T_ 前缀
    if (char.IsDigit(cleanName[0]))
        return $"T_{cleanName}";

    // 6. 如果包含非字母数字字符，添加 T_ 前缀
    if (cleanName.Any(c => !char.IsLetterOrDigit(c) && c != '_'))
        return $"T_{cleanName}";

    // 7. 如果是 SQL 关键字，添加 T_ 前缀
    var keywords = new[] { 
        "SELECT", "INSERT", "UPDATE", "DELETE", "DROP", "CREATE", "ALTER", "TABLE", 
        "FROM", "WHERE", "JOIN", "GROUP", "ORDER", "HAVING", "UNION", "INTERSECT", 
        "EXCEPT", "WITH", "VIEW", "INDEX", "PRIMARY", "FOREIGN", "KEY", "UNIQUE", 
        "CHECK", "DEFAULT", "NULL", "NOT", "AND", "OR", "IN", "LIKE", "BETWEEN", 
        "IS", "EXISTS", "ANY", "ALL", "SOME"
    };
    
    if (keywords.Contains(cleanName.ToUpperInvariant()))
        return $"T_{cleanName}";

    // 8. 检查长度限制
    if (cleanName.Length > 60)
        cleanName = cleanName.Substring(0, 60);

    return cleanName;
}

/// <summary>
/// 从所有导入的表中计算总金额
/// </summary>
private async Task<decimal> CalculateTotalAmountFromAllTablesAsync(List<string> tableNames)
{
    if (tableNames == null || tableNames.Count == 0)
        return 0;

    if (_databaseService == null)
        return 0;

    decimal total = 0;

    foreach (var tableName in tableNames)
    {
        try
        {
            // 查询表中所有金额列的数据
            var sql = $"SELECT \"{SelectedAmountKeyword}\" FROM \"{tableName}\"";
            var result = await _databaseService.ExecuteQueryAsync(sql, new List<object>());
            
            if (result != null && result.Count > 1)
            {
                // result[0] 是表头，从 result[1] 开始是数据
                for (int i = 1; i < result.Count; i++)
                {
                    if (result[i] != null && result[i].Count > 0)
                    {
                        var val = result[i][0]?.ToString()?.Trim() ?? "0";
                        val = val.Replace(",", "").Replace("，", "");
                        if (decimal.TryParse(val, out decimal num))
                        {
                            total += num;
                        }
                    }
                }
            }
        }
        catch
        {
        }
    }

    return total;
}

