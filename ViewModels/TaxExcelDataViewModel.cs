    private List<string> GetColumns(List<List<object>> data)
    {
        if (data == null || data.Count == 0 || data[0] == null)
            return new List<string>();

        var columns = new List<string>();
        foreach (var col in data[0])
        {
            var colName = col?.ToString()?.Trim() ?? $"Column{columns.Count + 1}";
            colName = SanitizeColumnName(colName);
            columns.Add(colName);
        }

        // 处理空列名
        var emptyColumns = columns.Where(c => string.IsNullOrEmpty(c)).ToList();
        if (emptyColumns.Any())
            return new List<string>();

        // 处理Id列
        for (int i = 0; i < columns.Count; i++)
        {
            if (columns[i].Equals("Id", StringComparison.OrdinalIgnoreCase))
                columns[i] = "Id_Data";
        }

        return columns;
    }

    private string GetTargetTableName(int idx, int currentColCount, string baseTableName, 
        ref int? baseColumnCount, ref int tableSuffix, Dictionary<int, string> columnSignatureMap)
    {
        if (idx == 0)
        {
            baseColumnCount = currentColCount;
            columnSignatureMap[currentColCount] = baseTableName;
            return baseTableName;
        }
        else if (currentColCount == baseColumnCount)
        {
            return baseTableName;
        }
        else if (columnSignatureMap.TryGetValue(currentColCount, out var existingName))
        {
            return existingName;
        }
        else
        {
            var newName = $"{baseTableName}_{tableSuffix}";
            tableSuffix++;
            columnSignatureMap[currentColCount] = newName;
            return newName;
        }
    }

