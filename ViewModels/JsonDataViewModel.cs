    #region 文件选择和预览

    private async Task SelectFileAsync()
    {
        if (_disposed || _isCleaned) return;

        CancelCurrentOperation();

        try
        {
            var window = GetWindow();
            if (window == null)
            {
                await ShowMessageBoxAsync("无法获取窗口句柄");
                return;
            }

            var filePath = await FileDialogHelper.OpenJsonFileAsync(window, "选择JSON文件");

            if (!string.IsNullOrEmpty(filePath))
            {
                await ThreadingHelper.RunOnUIThreadAsync(() =>
                {
                    if (_disposed || _isCleaned) return;
                    FilePath = filePath;
                    _currentFileName = Path.GetFileNameWithoutExtension(filePath);
                });
                await LoadPreviewAsync();
            }
        }
        catch (OperationCanceledException)
        {

        }
        catch (Exception ex)
        {
            await ShowMessageBoxAsync($"选择文件失败: {ex.Message}");

        }
    }

    private async Task LoadPreviewAsync()
    {
        if (_disposed || _isCleaned) return;
        if (_jsonService == null) return;

        CancelCurrentOperation();

        try
        {
            await ThreadingHelper.RunOnUIThreadAsync(() =>
            {
                if (_disposed || _isCleaned) return;
                IsLoading = true;
                SetStatus("正在加载预览...", new SolidColorBrush(Colors.Orange));
            });

            _cts = new CancellationTokenSource();
            var token = _cts.Token;

            var data = await _jsonService.ReadJsonAsync(FilePath);

            if (token.IsCancellationRequested || _disposed || _isCleaned) return;

            if (data == null || data.Count == 0)
            {
                await ShowMessageBoxAsync("文件为空或格式不正确");
                await ThreadingHelper.RunOnUIThreadAsync(() =>
                {
                    if (!_disposed && !_isCleaned) IsLoading = false;
                });
                return;
            }

            await ThreadingHelper.RunOnUIThreadAsync(() =>
            {
                if (_disposed || _isCleaned) return;

                var preview = new ObservableCollection<ObservableCollection<object>>();
                
                if (data.Count > 0 && data[0] != null)
                {
                    var headerRow = new ObservableCollection<object>();
                    foreach (var item in data[0])
                    {
                        headerRow.Add(item?.ToString() ?? string.Empty);
                    }
                    preview.Add(headerRow);
                }

                int maxRows = Math.Min(data.Count - 1, 20);
                for (int i = 1; i <= maxRows; i++)
                {
                    var row = new ObservableCollection<object>();
                    if (data[i] != null)
                    {
                        foreach (var item in data[i])
                        {
                            row.Add(item?.ToString() ?? string.Empty);
                        }
                    }
                    preview.Add(row);
                }

                PreviewData = preview;
                
                int totalRows = data.Count - 1;
                int totalCols = data[0]?.Count ?? 0;
                PreviewInfo = $"共 {totalRows} 行数据，{totalCols} 列";
                
                GenerateTableName();
                CanImport = true;
                IsLoading = false;
                SetStatus($"文件加载成功: {Path.GetFileName(FilePath)}", new SolidColorBrush(Colors.Green));
            });
        }
        catch (OperationCanceledException)
        {

            await ThreadingHelper.RunOnUIThreadAsync(() =>
            {
                if (!_disposed && !_isCleaned)
                {
                    IsLoading = false;
                    SetStatus("预览已取消", new SolidColorBrush(Colors.Orange));
                }
            });
        }
        catch (Exception ex)
        {

            await ThreadingHelper.RunOnUIThreadAsync(() =>
            {
                if (_disposed || _isCleaned) return;
                CanImport = false;
                IsLoading = false;
                SetStatus($"加载失败: {ex.Message}", new SolidColorBrush(Colors.Red));
            });
            await ShowMessageBoxAsync($"加载预览失败: {ex.Message}");
        }
    }

