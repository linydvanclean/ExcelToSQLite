    #region 导入

    private async Task ImportAsync()
    {
        if (_disposed || _isCleaned) return;
        if (IsLoading) return;
        if (_jsonService == null || _databaseService == null) return;

        try
        {
            if (string.IsNullOrEmpty(FilePath))
            {
                await ShowMessageBoxAsync("请先选择JSON文件");
                return;
            }

            if (SelectedBatch == null)
            {
                await ShowMessageBoxAsync("请先选择分析批次");
                return;
            }

            if (string.IsNullOrEmpty(TableName))
            {
                await ShowMessageBoxAsync("请输入表名或点击'自动生成'");
                return;
            }

            if (TableName.IndexOfAny(new[] { ' ', '-', '/', '\\', ':', '*', '?', '"', '<', '>', '|', '\'', ';' }) >= 0)
            {
                await ShowMessageBoxAsync("表名包含非法字符，请使用字母、数字和下划线");
                return;
            }

            if (!char.IsLetter(TableName[0]))
            {
                await ShowMessageBoxAsync("表名应以字母开头");
                return;
            }

            var confirmMessage = $"📊 确认导入数据\n\n" +
                                $"📁 文件: {Path.GetFileName(FilePath)}\n" +
                                $"📋 批次: {SelectedBatch.Name}\n" +
                                $"📝 表名: {TableName}\n" +
                                $"📅 创建时间: {SelectedBatch.CreatedAt:yyyy-MM-dd HH:mm}\n";

            if (UseDictionary && SelectedDictionary != null)
            {
                confirmMessage += $"📚 数据字典: {SelectedDictionary.Name}\n";
                if (!string.IsNullOrEmpty(SelectedDictionary.TableName))
                {
                    confirmMessage += $"🗄️ 字典表名: {SelectedDictionary.TableName}\n";
                }
            }

            confirmMessage += $"\n确认继续导入？";

            var confirm = await ShowConfirmDialogAsync(confirmMessage);
            if (!confirm) return;

            await ThreadingHelper.RunOnUIThreadAsync(() =>
            {
                if (_disposed || _isCleaned) return;
                IsLoading = true;
                SetStatus("正在导入数据...", new SolidColorBrush(Colors.Orange));
            });

            var data = await _jsonService.ReadJsonAsync(FilePath);
            
            if (data == null || data.Count <= 1)
            {
                await ShowMessageBoxAsync("没有数据可导入");
                await ThreadingHelper.RunOnUIThreadAsync(() =>
                {
                    if (!_disposed && !_isCleaned) IsLoading = false;
                });
                return;
            }

            var columns = new List<string>();
            if (data.Count > 0 && data[0] != null)
            {
                foreach (var col in data[0])
                {
                    var colName = col?.ToString()?.Trim() ?? $"Column{columns.Count + 1}";
                    columns.Add(colName);
                }
            }

            var emptyColumns = columns.Where(c => string.IsNullOrEmpty(c)).ToList();
            if (emptyColumns.Any())
            {
                await ShowMessageBoxAsync($"列名包含空值，请检查JSON文件。");
                await ThreadingHelper.RunOnUIThreadAsync(() =>
                {
                    if (!_disposed && !_isCleaned) IsLoading = false;
                });
                return;
            }

            if (columns.Any(c => c.Equals("Id", StringComparison.OrdinalIgnoreCase)))
            {
                await ShowMessageBoxAsync("列名中不能包含 'Id'，因为它是系统保留字段。请修改列名后再试。");
                await ThreadingHelper.RunOnUIThreadAsync(() =>
                {
                    if (!_disposed && !_isCleaned) IsLoading = false;
                });
                return;
            }

            await _databaseService.CreateTableAsync(TableName, columns);

            var rows = data.Skip(1).ToList();
            await _databaseService.InsertDataAsync(TableName, columns, rows);

            await ThreadingHelper.RunOnUIThreadAsync(async () =>
            {
                if (_disposed || _isCleaned) return;

                var message = $"✅ 导入成功!\n\n" +
                             $"📝 表名: {TableName}\n" +
                             $"📋 批次: {SelectedBatch.Name}\n" +
                             $"📊 导入行数: {rows.Count}\n" +
                             $"📑 列数: {columns.Count}\n" +
                             $"🕐 导入时间: {DateTime.Now:yyyy-MM-dd HH:mm:ss}";

                if (UseDictionary && SelectedDictionary != null)
                {
                    message += $"\n📚 数据字典: {SelectedDictionary.Name}";
                }
                
                await ShowMessageBoxAsync(message);
                
                PreviewInfo = $"✅ 已导入 {rows.Count} 行数据到表 {TableName} (批次: {SelectedBatch.Name})";
                SetStatus($"✅ 导入成功: {rows.Count} 行数据", new SolidColorBrush(Colors.Green));
                IsLoading = false;
            });
        }
        catch (Exception ex)
        {

            await ThreadingHelper.RunOnUIThreadAsync(async () =>
            {
                if (_disposed || _isCleaned) return;
                var errorMsg = $"导入失败: {ex.Message}";
                await ShowMessageBoxAsync(errorMsg);
                SetStatus($"❌ {errorMsg}", new SolidColorBrush(Colors.Red));
                IsLoading = false;
            });
        }
    }

