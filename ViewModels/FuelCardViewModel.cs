        #region 初始化

        private async Task InitializeAsync()
        {
            if (_disposed || _isCleaned) return;

            await _lock.WaitAsync();
            try
            {
                if (_disposed || _isCleaned) return;

                _cts = new CancellationTokenSource();
                var token = _cts.Token;

                var loadBatchesTask = LoadBatchesAsync();
                var loadDictionariesTask = LoadDictionariesAsync();

                await Task.WhenAll(loadBatchesTask, loadDictionariesTask);

                if (!token.IsCancellationRequested && !_disposed && !_isCleaned)
                {
                    SetStatus("初始化完成", new SolidColorBrush(Colors.Green));
                }
            }
            catch (OperationCanceledException)
            {
            }
            catch (Exception ex)
            {
                await SetStatusAsync($"初始化失败: {ex.Message}", new SolidColorBrush(Colors.Red));
            }
            finally
            {
                _lock.Release();
            }
        }

