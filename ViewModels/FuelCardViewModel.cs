        #region ICleanupPage 实现

        public void Cleanup()
        {
            if (_isCleaned) return;

            try
            {
                CancelCurrentOperation();

                _lock.Wait(TimeSpan.FromSeconds(2));
                try
                {
                    _subscriptions?.Dispose();

                    _ = ThreadingHelper.RunOnUIThreadAsync(() =>
                    {
                        try
                        {
                            Batches?.Clear();
                            DataDictionaries?.Clear();
                            SelectedFiles?.Clear();
                            SelectedBatch = null;
                            SelectedDictionary = null;
                            StatusMessage = string.Empty;
                            ShowStatus = false;
                            FilePath = string.Empty;
                            TableName = string.Empty;
                            TableNameInfo = string.Empty;
                            TableNameValidation = string.Empty;
                            ShowValidation = false;
                            _currentFileName = null;
                            _isAutoGenerated = false;
                            CanImport = false;
                            UseDictionary = false;
                            IsLoading = false;
                            LoadingMessage = string.Empty;
                            ShowImportStats = false;
                            ImportStatsText = string.Empty;
                            _allRecords.Clear();
                            FileCount = 0;
                            TotalRecords = 0;
                            CardCount = 0;
                            TotalAmount = 0;
                            TotalFuelVolume = 0;
                            TotalAmountDisplay = "0.00";
                            FuelRecordCount = 0;
                            DepositRecordCount = 0;
                        }
                        catch { }
                    });

                    _isCleaned = true;
                }
                finally
                {
                    try { _lock.Release(); } catch { }
                }
            }
            catch
            {
                _isCleaned = true;
            }
        }

        #endregion

        #region IDisposable 实现

        public void Dispose()
        {
            if (_disposed) return;

            try
            {
                Cleanup();
                _lock?.Dispose();
                _cts?.Dispose();
                _cts = null;
                _disposed = true;
            }
            catch
            {
                _disposed = true;
            }

            GC.SuppressFinalize(this);
        }

