        private async Task ParseAllFilesAsync(List<string> filePaths)
        {
            if (_disposed || _isCleaned) return;
            if (_parserService == null) return;

            CancelCurrentOperation();

            try
            {
                await ThreadingHelper.RunOnUIThreadAsync(() =>
                {
                    if (_disposed || _isCleaned) return;
                    IsLoading = true;
                    LoadingMessage = "正在解析加油卡文件...";
                    SetStatus("正在解析加油卡文件...", new SolidColorBrush(Colors.Orange));
                });

                _cts = new CancellationTokenSource();
                var token = _cts.Token;

                var allRecords = new List<FuelCardRecord>();
                int processedFiles = 0;
                var fileResults = new List<string>();

                foreach (var filePath in filePaths)
                {
                    if (token.IsCancellationRequested || _disposed || _isCleaned) break;

                    var fileName = Path.GetFileName(filePath);
                    processedFiles++;

                    await ThreadingHelper.RunOnUIThreadAsync(() =>
                    {
                        LoadingMessage = $"正在解析: {fileName} ({processedFiles}/{filePaths.Count})";
                    });

                    try
                    {
                        var records = await _parserService.ParseFuelCardAsync(filePath);
                        var validRecords = records.Where(r => r.IsValidRecord).ToList();
                        
                        allRecords.AddRange(validRecords);
                        fileResults.Add($"✅ {fileName}: {validRecords.Count} 条记录");
                    }
                    catch (Exception ex)
                    {
                        fileResults.Add($"❌ {fileName}: {ex.Message}");
                    }
                }

                if (token.IsCancellationRequested || _disposed || _isCleaned) return;

                // 更新统计信息
                _allRecords = allRecords;
                TotalRecords = allRecords.Count;
                CardCount = allRecords.Select(r => r.CardNumber).Distinct().Count();
                TotalAmount = allRecords.Sum(r => r.Amount);
                TotalFuelVolume = allRecords.Sum(r => r.Quantity);
                TotalAmountDisplay = TotalAmount.ToString("N2");
                
                // 统计圈存和加油记录数量
                FuelRecordCount = allRecords.Count(r => r.BusinessType == "加油");
                DepositRecordCount = allRecords.Count(r => r.BusinessType == "圈存");

                await ThreadingHelper.RunOnUIThreadAsync(() =>
                {
                    if (_disposed || _isCleaned) return;
                    
                    GenerateTableName();
                    ValidateTableName();
                    CanImport = allRecords.Count > 0;
                    IsLoading = false;
                    LoadingMessage = string.Empty;
                    
                    var summary = $"✅ 解析完成！共 {allRecords.Count} 条记录，" +
                                  $"其中加油 {FuelRecordCount} 条，圈存 {DepositRecordCount} 条，" +
                                  $"{CardCount} 张卡，总金额 {TotalAmount:N2} 元";
                    SetStatus(summary, new SolidColorBrush(Colors.Green));
                    
                    // 如果有错误，显示警告
                    if (fileResults.Any(r => r.Contains("❌")))
                    {
                        var errors = string.Join("\n", fileResults.Where(r => r.Contains("❌")));
                        _ = ShowWarningMessageAsync($"部分文件解析失败:\n{errors}", "解析警告");
                    }
                });
            }
            catch (OperationCanceledException)
            {
                await ThreadingHelper.RunOnUIThreadAsync(() =>
                {
                    if (!_disposed && !_isCleaned)
                    {
                        IsLoading = false;
                        LoadingMessage = string.Empty;
                        SetStatus("解析已取消", new SolidColorBrush(Colors.Orange));
                    }
                });
            }
            catch (Exception ex)
            {
                await ThreadingHelper.RunOnUIThreadAsync(async () =>
                {
                    if (_disposed || _isCleaned) return;
                    await ShowErrorMessageAsync($"解析失败: {ex.Message}", "解析失败");
                    SetStatus($"❌ 解析失败: {ex.Message}", new SolidColorBrush(Colors.Red));
                    CanImport = false;
                    IsLoading = false;
                    LoadingMessage = string.Empty;
                });
            }
        }

