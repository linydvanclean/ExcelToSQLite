                });
            }
            catch (Exception ex)
            {
                await ThreadingHelper.RunOnUIThreadAsync(() =>
                {
                    if (_disposed || _isCleaned) return;
                    SetStatus($"加载数据字典失败: {ex.Message}", new SolidColorBrush(Colors.Red));
                    DictionaryInfo = "加载数据字典失败";
                });
            }
        }

