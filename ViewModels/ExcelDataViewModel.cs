    public void Dispose()
    {
        if (_disposed) return;

        try
        {
            Cleanup();
            _lock?.Dispose();
            _cts?.Dispose();
            _cts = null;
            _disposed = true;
        }
        catch
        {
            _disposed = true;
        }

        GC.SuppressFinalize(this);
    }

