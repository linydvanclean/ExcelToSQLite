    private static string SanitizeColumnName(string colName)
    {
        if (string.IsNullOrEmpty(colName))
            return "Column";

        var result = colName
            .Replace("、", "")
            .Replace("（", "")
            .Replace("）", "")
            .Replace("【", "")
            .Replace("】", "")
            .Replace("《", "")
            .Replace("》", "")
            .Replace("，", "")
            .Replace("。", "")
            .Replace("；", "")
            .Replace("：", "")
            .Replace("？", "")
            .Replace("！", "")
            .Replace("…", "")
            .Replace("·", "")
            .Replace("'", "")
            .Replace("\"", "")
            .Replace("/", "_")
            .Replace("\\", "_")
            .Replace("(", "")
            .Replace(")", "")
            .Replace("[", "")
            .Replace("]", "")
            .Replace("<", "")
            .Replace(">", "")
            .Replace("*", "")
            .Replace("?", "")
            .Replace(":", "_")
            .Replace("#", "")
            .Replace("%", "")
            .Replace("&", "_")
            .Replace("+", "_")
            .Replace("=", "_")
            .Replace("|", "_")
            .Trim();

        if (result.Length > 0 && char.IsDigit(result[0]))
        {
            result = "C" + result;
        }

        return string.IsNullOrEmpty(result) ? "Column" : result;
    }

