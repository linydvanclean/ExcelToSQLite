    #region 文件选择

    private async Task SelectFileAsync()
    {
        if (_disposed || _isCleaned) return;

        CancelCurrentOperation();

        try
        {
            var window = GetWindow();
            if (window == null)
            {
                await ShowMessageBoxAsync("无法获取窗口句柄");
                return;
            }

            var filePaths = await OpenMultipleExcelFilesAsync(window, "选择Excel文件（可多选）");

            if (filePaths != null && filePaths.Count > 0)
            {
                if (filePaths.Count > 0)
                {
                    _lastOpenDirectory = Path.GetDirectoryName(filePaths[0]);
                }

                var primaryFilePath = filePaths[0];

                await ThreadingHelper.RunOnUIThreadAsync(() =>
                {
                    if (_disposed || _isCleaned) return;
                    FilePath = primaryFilePath;
                    _currentFileName = Path.GetFileNameWithoutExtension(primaryFilePath);
                    SelectedFiles = new ObservableCollection<string>(filePaths.Select(f => Path.GetFileName(f) ?? f));
                    FileCount = filePaths.Count;
                    GenerateTableName();
                });

                await ParseFileInfoAsync();
            }
        }
        catch (OperationCanceledException)
        {
        }
        catch (Exception ex)
        {
            await ShowMessageBoxAsync($"选择文件失败: {ex.Message}");
        }
    }

    private async Task<List<string>?> OpenMultipleExcelFilesAsync(Window? parent, string title)
    {
        if (parent == null || !parent.IsVisible || parent.WindowState == WindowState.Minimized)
            return null;

        var storageProvider = parent.StorageProvider;
        if (storageProvider == null) return null;

        var options = new Avalonia.Platform.Storage.FilePickerOpenOptions
        {
            Title = title,
            AllowMultiple = true,
            SuggestedStartLocation = !string.IsNullOrEmpty(_lastOpenDirectory) 
                ? await storageProvider.TryGetFolderFromPathAsync(new Uri(_lastOpenDirectory))
                : null,
            FileTypeFilter = new List<Avalonia.Platform.Storage.FilePickerFileType>
            {
                new("Excel 文件 (*.xlsx, *.xls)")
                {
                    Patterns = new List<string> { "*.xlsx", "*.xls" }
                },
                new("所有文件 (*.*)")
                {
                    Patterns = new List<string> { "*" }
                }
            }
        };

        try
        {
            using var cts = new CancellationTokenSource(TimeSpan.FromSeconds(30));
            var files = await storageProvider.OpenFilePickerAsync(options).WaitAsync(cts.Token);
            if (files != null && files.Count > 0)
            {
                return files.Select(f => f.Path?.LocalPath ?? f.Name).ToList();
            }
        }
        catch
        {
        }

        return null;
    }

