/// <summary>
/// 提取列名
/// </summary>
private List<string> ExtractColumns(List<List<object>> data)
{
    if (data == null || data.Count == 0 || data[0] == null)
        return new List<string>();

    var columns = new List<string>();
    foreach (var col in data[0])
    {
        var colName = col?.ToString()?.Trim() ?? $"Column{columns.Count + 1}";
        colName = SanitizeColumnName(colName);
        columns.Add(colName);
    }

    // 检查是否有空列名
    if (columns.Any(string.IsNullOrEmpty))
        return new List<string>();

    // 处理 Id 列冲突
    for (int i = 0; i < columns.Count; i++)
    {
        if (columns[i].Equals("Id", StringComparison.OrdinalIgnoreCase))
            columns[i] = "Id_Data";
    }

    return columns;
}

/// <summary>
/// 生成结构签名（用于比较表结构）
/// </summary>
private string GenerateStructureSignature(List<string> columns)
{
    if (columns == null || columns.Count == 0)
        return string.Empty;
    
    // 按列名排序并拼接，确保相同列集合产生相同签名
    var sortedColumns = columns.Select(c => c.ToLowerInvariant()).OrderBy(c => c);
    return string.Join("|", sortedColumns);
}

/// <summary>
/// 比较两列是否相等
/// </summary>
private bool AreColumnsEqual(List<string> columns1, List<string> columns2)
{
    if (columns1 == null && columns2 == null) return true;
    if (columns1 == null || columns2 == null) return false;
    if (columns1.Count != columns2.Count) return false;
    
    // 忽略大小写比较
    for (int i = 0; i < columns1.Count; i++)
    {
        if (!string.Equals(columns1[i], columns2[i], StringComparison.OrdinalIgnoreCase))
            return false;
    }
    return true;
}

/// <summary>
/// 从文件名生成表名（不使用 ref 参数）
/// </summary>
private string GenerateTableNameFromFileName(string fileName, string baseTableName)
{
    if (string.IsNullOrEmpty(fileName))
        return $"{baseTableName}_File";

    // 1. 清理文件名（替换非法字符为下划线）
    var cleanName = fileName
        .Replace(" ", "_")
        .Replace("-", "_")
        .Replace("/", "_")
        .Replace("\\", "_")
        .Replace(":", "_")
        .Replace("*", "_")
        .Replace("?", "_")
        .Replace("\"", "_")
        .Replace("<", "_")
        .Replace(">", "_")
        .Replace("|", "_")
        .Replace("'", "_")
        .Replace(";", "_")
        .Replace("(", "_")
        .Replace(")", "_")
        .Replace("[", "_")
        .Replace("]", "_")
        .Replace("{", "_")
        .Replace("}", "_")
        .Replace("+", "_")
        .Replace("=", "_")
        .Replace("&", "_")
        .Replace("%", "_")
        .Replace("#", "_")
        .Replace("@", "_")
        .Replace("!", "_")
        .Replace("$", "_")
        .Replace("`", "_")
        .Replace("~", "_")
        .Replace("^", "_");

    // 2. 合并多个下划线
    while (cleanName.Contains("__"))
        cleanName = cleanName.Replace("__", "_");

    // 3. 去除首尾下划线
    cleanName = cleanName.Trim('_');

    // 4. 如果为空，使用默认名称
    if (string.IsNullOrEmpty(cleanName))
        return $"{baseTableName}_File";

    // 5. 如果以数字开头，添加 T_ 前缀
    if (char.IsDigit(cleanName[0]))
        return $"T_{cleanName}";

    // 6. 如果包含非字母数字字符，添加 T_ 前缀
    if (cleanName.Any(c => !char.IsLetterOrDigit(c) && c != '_'))
        return $"T_{cleanName}";

    // 7. 如果是 SQL 关键字，添加 T_ 前缀
    var keywords = new[] { "SELECT", "INSERT", "UPDATE", "DELETE", "DROP", "CREATE", "ALTER", "TABLE", "FROM", "WHERE", 
                           "JOIN", "GROUP", "ORDER", "HAVING", "UNION", "INTERSECT", "EXCEPT", "WITH", "VIEW", "INDEX",
                           "PRIMARY", "FOREIGN", "KEY", "UNIQUE", "CHECK", "DEFAULT", "NULL", "NOT", "AND", "OR", "IN",
                           "LIKE", "BETWEEN", "IS", "EXISTS", "ANY", "ALL", "SOME" };
    if (keywords.Contains(cleanName.ToUpperInvariant()))
        return $"T_{cleanName}";

    // 8. 检查长度限制
    if (cleanName.Length > 60)
        cleanName = cleanName.Substring(0, 60);

    return cleanName;
}
    

