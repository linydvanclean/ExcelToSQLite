    #region 数据加载

    private async Task LoadBatchesAsync()
    {
        if (_disposed || _isCleaned) return;
        if (_batchService == null) return;

        try
        {
            await ThreadingHelper.RunOnUIThreadAsync(() =>
            {
                if (_disposed || _isCleaned) return;
                IsLoading = true;
                LoadingMessage = "正在加载批次...";
                SetStatus("正在加载批次...", new SolidColorBrush(Colors.Orange));
            });

            var list = await _batchService.GetAllAsync(1000);
            var sortedList = list.OrderByDescending(b => b.CreatedAt).ToList();
            
            await ThreadingHelper.RunOnUIThreadAsync(() =>
            {
                if (_disposed || _isCleaned) return;
                Batches = new ObservableCollection<AnalysisBatch>(sortedList);
            
                if (Batches.Count > 0)
                {
                    SelectedBatch = Batches[0];
                    BatchInfo = $"共 {Batches.Count} 个批次，已选择最新的批次: {SelectedBatch.Name}";
                
                    if (!string.IsNullOrEmpty(_currentFileName))
                    {
                        GenerateTableName();
                    }
                }
                else
                {
                    BatchInfo = "暂无批次，请创建批次";
                    SelectedBatch = null;
                }
                
                IsLoading = false;
                LoadingMessage = string.Empty;
                SetStatus("批次加载完成", new SolidColorBrush(Colors.Green));
            });
        }
        catch (Exception ex)
        {
            await ThreadingHelper.RunOnUIThreadAsync(() =>
            {
                if (_disposed || _isCleaned) return;
                SetStatus($"加载批次失败: {ex.Message}", new SolidColorBrush(Colors.Red));
                BatchInfo = "加载批次失败";
                SelectedBatch = null;
                IsLoading = false;
                LoadingMessage = string.Empty;
            });
        }
    }

