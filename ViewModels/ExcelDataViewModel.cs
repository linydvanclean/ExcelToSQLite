    private async Task ImportAsync()
{
    if (_disposed || _isCleaned) return;
    if (IsLoading) return;
    if (_excelService == null || _databaseService == null) return;

    try
    {
        // 1. 验证基本条件
        if (string.IsNullOrEmpty(FilePath))
        {
            await ShowMessageBoxAsync("请先选择Excel文件");
            return;
        }

        if (SelectedBatch == null)
        {
            await ShowMessageBoxAsync("请先选择分析批次");
            return;
        }

        if (string.IsNullOrEmpty(TableName))
        {
            await ShowMessageBoxAsync("请输入表名或点击'自动生成'");
            return;
        }

        // 2. 验证表名合法性
        if (TableName.IndexOfAny(new[] { ' ', '-', '/', '\\', ':', '*', '?', '"', '<', '>', '|', '\'', ';' }) >= 0)
        {
            await ShowMessageBoxAsync("表名包含非法字符，请使用字母、数字和下划线");
            return;
        }

        if (!char.IsLetter(TableName[0]))
        {
            await ShowMessageBoxAsync("表名应以字母开头");
            return;
        }

        // 3. 确认对话框
        var confirmMessage = $"📊 确认导入数据\n\n" +
                            $"📁 文件数: {FileCount}\n" +
                            $"📋 批次: {SelectedBatch.Name}\n" +
                            $"📝 基础表名: {TableName}\n" +
                            $"📊 数据行数: {TotalRows}\n" +
                            $"📅 创建时间: {SelectedBatch.CreatedAt:yyyy-MM-dd HH:mm}\n";

        if (UseDictionary && SelectedDictionary != null)
        {
            confirmMessage += $"📚 数据字典: {SelectedDictionary.Name}\n";
        }

        confirmMessage += $"\n⚠️ 说明：\n" +
                         $"- 结构相同的文件将合并到同一张表\n" +
                         $"- 结构不同的文件将使用文件名单独建表\n" +
                         $"\n确认继续导入？";
        
        var confirm = await ShowConfirmDialogAsync(confirmMessage);
        if (!confirm) return;

        // 4. 准备导入
        await ThreadingHelper.RunOnUIThreadAsync(() =>
        {
            if (_disposed || _isCleaned) return;
            IsLoading = true;
            LoadingMessage = "正在准备导入...";
            SetStatus("正在导入数据...", new SolidColorBrush(Colors.Orange));
        });

        // 5. 获取所有需要导入的文件
        var filesToImport = GetFilesToImport();
        
        int totalImportedRows = 0;
        var importedTables = new List<string>();
        var importResults = new List<string>();

        // 6. 用于跟踪表结构和表名映射
        var tableStructureMap = new Dictionary<string, List<string>>(); // 表名 -> 列结构签名
        var structureSignatureMap = new Dictionary<string, string>(); // 结构签名 -> 表名
        var usedTableNames = new HashSet<string>();
        
        // 记录第一个文件的列结构作为基准
        List<string>? baseColumns = null;
        string? baseTableName = TableName;

        // 7. 处理每个文件
        for (int idx = 0; idx < filesToImport.Count; idx++)
        {
            var filePath = filesToImport[idx];
            var fileName = Path.GetFileNameWithoutExtension(filePath);
            
            await ThreadingHelper.RunOnUIThreadAsync(() =>
            {
                LoadingMessage = $"正在处理: {fileName} ({idx + 1}/{filesToImport.Count})";
            });

            // 读取Excel数据
            var data = await _excelService.ReadExcelAsync(filePath);
            if (data == null || data.Count <= 1)
            {
                importResults.Add($"⚠️ {Path.GetFileName(filePath)}: 没有数据可导入");
                continue;
            }

            // 提取列名
            var columns = ExtractColumns(data);
            if (columns == null || columns.Count == 0)
            {
                importResults.Add($"⚠️ {Path.GetFileName(filePath)}: 列名无效，跳过");
                continue;
            }

            // 生成结构签名
            var structureSignature = GenerateStructureSignature(columns);
            int columnCount = columns.Count;

            // 8. 确定目标表名（核心逻辑）
            string targetTableName;
            
            // 8.1 第一个文件：使用用户定义的表名
            if (idx == 0)
            {
                targetTableName = baseTableName;
                baseColumns = columns;
                
                // 记录结构和表名映射
                structureSignatureMap[structureSignature] = targetTableName;
                tableStructureMap[targetTableName] = columns;
                usedTableNames.Add(targetTableName);
            }
            // 8.2 检查是否与第一个文件结构一致
            else if (baseColumns != null && AreColumnsEqual(baseColumns, columns))
            {
                targetTableName = baseTableName;
                importResults.Add($"🔄 {Path.GetFileName(filePath)}: 结构与基础表一致，合并到 {targetTableName}");
            }
            // 8.3 检查是否与已处理的其他文件结构一致
            else if (structureSignatureMap.TryGetValue(structureSignature, out var existingTableName))
            {
                targetTableName = existingTableName;
                importResults.Add($"🔄 {Path.GetFileName(filePath)}: 结构与已有表一致，合并到 {targetTableName}");
            }
            // 8.4 结构不同：使用文件名作为表名
            else
            {
                // 生成基于文件名的表名
                var fileBasedTableName = GenerateTableNameFromFileName(fileName, baseTableName!);
    
                // 检查是否已存在该表名
                if (usedTableNames.Contains(fileBasedTableName))
                {
                    // 如果表名已存在，添加后缀
                    int suffix = 1;
                    string newTableName;
                    do
                    {
                        newTableName = $"{fileBasedTableName}_{suffix}";
                        suffix++;
                    } while (usedTableNames.Contains(newTableName));
                    fileBasedTableName = newTableName;
                }
    
                targetTableName = fileBasedTableName;
    
                // 记录新结构和表名
                structureSignatureMap[structureSignature] = targetTableName;
                tableStructureMap[targetTableName] = columns;
                usedTableNames.Add(targetTableName);
    
                importResults.Add($"📝 {Path.GetFileName(filePath)}: 使用独立表名 {targetTableName} ({columnCount} 列)");
            }

            // 9. 执行导入
            // 创建表（如果不存在）
            await _databaseService.CreateTableAsync(targetTableName, columns);

            // 插入数据
            var rows = data.Skip(1).ToList();
            await _databaseService.InsertDataAsync(targetTableName, columns, rows);

            totalImportedRows += rows.Count;
            importedTables.Add(targetTableName);
        }

        // 10. 显示导入结果
        await ThreadingHelper.RunOnUIThreadAsync(() =>
        {
            if (_disposed || _isCleaned) return;

            var message = $"✅ 导入完成!\n\n" +
                         $"📁 文件数: {filesToImport.Count}\n" +
                         $"📝 表数: {importedTables.Distinct().Count()}\n" +
                         $"📊 总行数: {totalImportedRows}\n" +
                         $"🕐 导入时间: {DateTime.Now:yyyy-MM-dd HH:mm:ss}\n\n" +
                         $"详情:\n{string.Join("\n", importResults)}";

            ShowImportStats = true;
            ImportStatsText = message;
            SetStatus($"✅ 导入成功: {totalImportedRows} 行数据", new SolidColorBrush(Colors.Green));
            IsLoading = false;
            LoadingMessage = string.Empty;
        });
    }
    catch (Exception ex)
    {
        await ThreadingHelper.RunOnUIThreadAsync(async () =>
        {
            if (_disposed || _isCleaned) return;
            var errorMsg = $"导入失败: {ex.Message}";
            await ShowMessageBoxAsync(errorMsg);
            SetStatus($"❌ {errorMsg}", new SolidColorBrush(Colors.Red));
            IsLoading = false;
            LoadingMessage = string.Empty;
        });
    }
}
    
